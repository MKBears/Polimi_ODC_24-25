# This exploit exactly follows the challenge logical flow: xores stuff to update a temporary vector and then prints the flag (which is an elaborated version of the temporary vector)

flag_len = 36

# offset 0x2020
indices = [0x11,0x3,0x18,0x9,0x0C,0x1C,0x23,0x5,0x16,0x0E,0x1,0x20,0x12,0x0A,0x1E,0x19,0x0B,0x2,0x1B,0x6,0x0,0x21,0x0D,0x15,0x7,0x8,0x0F,0x22,0x14,0x17,0x1F,0x13,0x1A,0x1D,0x4,0x10,0x0]

# offset 0x2060
vec = [0x69,0x42,0x26,0xFD,0xDA,0xBE,0x52,0x84,0x3A,0x31,0xFC,0xF1,0xCD,0x0A,0xA8,0xA1,0x6B,0x2E,0xE8,0x25,0x24,0xB8,0x62,0x84,0x4A,0x34,0xDE,0x1E,0xBC,0xAF,0xF8,0x96,0x38,0x67,0x40,0x17]

# offset 0x4020
temp = [0x42, 0x49, 0x50, 0x57, 0x5E, 0x65, 0x6C, 0x73, 0x7A, 0x81, 0x88, 0x8F, 0x96, 0x9D, 0xA4, 0xAB, 0xB2, 0xB9, 0xC0, 0xC7, 0xCE, 0xD5, 0xDC, 0xE3, 0xEA, 0xF1, 0xF8, 0xFF, 0x6, 0x0D, 0x14, 0x1B, 0x22, 0x29, 0x30, 0x37]

# updating the temporary vector (already initialized)
for i in range(flag_len):
    index = indices[i]
    temp[index] = (115 * index) ^ (((31 * index + 90) ^ (vec[index] - 45)) + 17)

flag = ''

# putting the flag together
for i in range(36):
    character = temp[i] ^ (i * 0x73)
    character -= 0x11
    print(hex(character))   # debug
    character &= 0xff       # logical and to neglect overflow
    print(hex(character))   # debug
    flag += int.to_bytes(character).decode()

print(flag)